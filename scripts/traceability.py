"""Write TRACEABILITY.md: every exercise and capstone, its book chapter, repository path, the command that runs it,
and the expected result recorded by the last full run (`output/<path>/result.json`).

usage:
  python scripts/traceability.py           # regenerate TRACEABILITY.md
  python scripts/traceability.py --check   # fail if TRACEABILITY.md is stale or an exercise has no recorded result
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "TRACEABILITY.md"


def rows() -> tuple[list[str], list[str]]:
    lines, problems = [], []
    metas = sorted(ROOT.glob("exercises/ch*/ex*/meta.json"), key=lambda p: p.parent.name) + sorted(
        ROOT.glob("capstones/c*/meta.json"))
    for meta_path in metas:
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
        rel = meta_path.parent.relative_to(ROOT).as_posix()
        if rel.startswith("exercises/"):
            chapter = int(meta["chapter"][2:4])
            where = f"Ch {chapter}"
            command = f"`python scripts/check.py --solutions {rel}`"
        else:
            where = "Appendix D"
            command = f"`python scripts/check.py --solutions {rel}`"
        result = ROOT / "output" / rel / "result.json"
        if result.exists():
            r = json.loads(result.read_text(encoding="utf-8"))
            t = r["tests"]
            expected = f"{r['status']}: {t['passed']} passed, {t['failed']} failed; starter fails {r.get('starter_failing', '?')}"
        else:
            expected = "no recorded run"
            problems.append(f"{rel}: no output/{rel}/result.json; run scripts/run_all.py")
        lines.append(f"| {meta['id']} | {where} | {meta['title']} | `{rel}/` | {command} | {expected} |")
    return lines, problems


def render() -> tuple[str, list[str]]:
    body, problems = rows()
    head = ["# Traceability: book → repository → command → expected result", "",
            "Generated by `python scripts/traceability.py` from each `meta.json` and the last full run "
            "(`python scripts/run_all.py`). Run your own work with `python scripts/check.py <path>` (without "
            "`--solutions`); it starts red.", "",
            "| Id | Book | Title | Path | Command | Expected result (reference solution) |",
            "|---|---|---|---|---|---|"]
    return "\n".join(head + body) + "\n", problems


def main(argv: list[str]) -> int:
    text, problems = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            problems.append("TRACEABILITY.md is stale: run python scripts/traceability.py")
    else:
        OUT.write_text(text, encoding="utf-8")
    for p in problems:
        print(p)
    print(f"traceability: {text.count(chr(10) + '| ') - 1} rows, {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
